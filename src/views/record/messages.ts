export type RecordMessageKey = keyof typeof RECORD_MESSAGES.en;

export function formatRecordMessage(
  locale: RecordLocale,
  key: RecordMessageKey,
  params?: Readonly<Record<string, string | number>>,
): string {
  const dictionary = RECORD_MESSAGES[locale] ?? RECORD_MESSAGES.en;
  if (key === 'unsavedChangesCount' && params?.['count'] === 1) {
    return dictionary.unsavedChangesSingle;
  }
  const template = dictionary[key] ?? RECORD_MESSAGES.en[key];
  if (!params) {
    return template;
  }
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, token: string) => {
    const replacement = params[token];
    return replacement === undefined ? `{${token}}` : String(replacement);
  });
}

export function formatRecordInteger(locale: RecordLocale, value: number): string {
  // Biçim dili dil eşleme dosyasından gelir (IC-13).
  return new Intl.NumberFormat(localeBundle(locale).intl, { maximumFractionDigits: 0 }).format(
    value,
  );
}
